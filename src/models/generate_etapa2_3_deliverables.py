def update_official_xlsm_etapa2(
    mart: dict[str, Any] | None = None, xlsm_path: Path = OFFICIAL_XLSM_PATH
) -> Path:
    """Update Row 3 columns B..H in 'Projeto Final Etapa 2 - Modelag' preserving workbook structure."""
    payload = mart if mart is not None else load_mart_payload()
    cell_texts = build_etapa2_cell_texts(payload)
    wb = openpyxl.load_workbook(xlsm_path, keep_vba=True)
    ws = wb[ETAPA2_SHEET_NAME]

    for col_letter, text in cell_texts.items():
        cell = ws[f"{col_letter}3"]
        cell.value = text
        cur_align = cell.alignment
        cell.alignment = Alignment(
            horizontal=cur_align.horizontal or "left",
            vertical="top",
            wrap_text=True,
        )

    ws.row_dimensions[3].height = 290
    wb.save(xlsm_path)
    return xlsm_path


