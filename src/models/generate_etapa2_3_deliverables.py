def _fmt_pct_pt(val: float, decimals: int = 2) -> str:
    """Format a decimal probability ratio into Portuguese comma-separated percentage."""
    return f"{val * 100:.{decimals}f}%".replace(".", ",")


def _fmt_num_pt(val: int) -> str:
    """Format integer with dot thousands separator in Portuguese convention."""
    return f"{val:,}".replace(",", ".")


def _scenario_map(mart: dict[str, Any]) -> dict[str, dict[str, Any]]:
    """Index scenario records by scenario_code."""
    return {r["scenario_code"]: r for r in mart["scenarios"]}


def _critical_theta_threshold(curve: list[dict[str, Any]]) -> tuple[float, float]:
    """Return (last_nash_theta, first_shift_theta) for a scenario sensitivity curve."""
    base_v = float(curve[0]["game_value_v_primal"])
    base_p = (
        float(curve[0].get("gk_opt_L", 0.0)),
        float(curve[0].get("gk_opt_C", 0.0)),
        float(curve[0].get("gk_opt_R", 0.0)),
    )
    last_nash = float(curve[0]["theta"])
    first_shift = float(curve[-1]["theta"])
    for pt in curve:
        v_diff = abs(float(pt["game_value_v_primal"]) - base_v)
        p_diff = max(
            abs(float(pt.get("gk_opt_L", base_p[0])) - base_p[0]),
            abs(float(pt.get("gk_opt_C", base_p[1])) - base_p[1]),
            abs(float(pt.get("gk_opt_R", base_p[2])) - base_p[2]),
        )
        if v_diff <= 1e-4 and p_diff <= 1e-4:
            last_nash = float(pt["theta"])
        else:
            first_shift = float(pt["theta"])
            break
    return last_nash, first_shift


